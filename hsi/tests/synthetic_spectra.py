def demo_spectrum(label, wl, rng=None):
    rng = rng or np.random.default_rng(0)
    key = next((k for k in sorted(_DEMO_BANDS, key=len, reverse=True)
                if k.lower() in label.lower()), None)
    base = 0.35 + 0.05 * (wl - 1000) / 2900 + rng.normal(0, 0.0015, wl.size)
    r = np.ones_like(wl)
    for c, d, f in _DEMO_BANDS.get(key, []):
        r *= 1 - d * np.exp(-0.5 * ((wl - c) / (f / 2.3548)) ** 2)
    return base * r


